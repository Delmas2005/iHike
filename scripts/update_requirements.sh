#!/usr/bin/env bash
# Regenerate requirements.txt, the pinned list the Hugging Face Space installs.
#
# Resolved from pyproject.toml (core + ai) for Python 3.11 on Linux x86_64, together with the
# gradio version of the Space SDK. CUDA packages are dropped: the Space has no GPU, and the
# --extra-index-url line makes pip take the CPU build of the same torch version.
# Needs uv (https://docs.astral.sh/uv/).
set -euo pipefail
cd "$(dirname "$0")/.."

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
uv pip compile pyproject.toml scripts/space.in --extra ai \
    --python-version 3.11 --python-platform x86_64-manylinux_2_28 \
    --no-header --no-annotate --quiet -o "$tmp"

{
    echo "# Generated by scripts/update_requirements.sh from pyproject.toml - do not edit by hand."
    echo "# CPU-only PyTorch for the Space:"
    echo "--extra-index-url https://download.pytorch.org/whl/cpu"
    grep -vE '^(nvidia-|triton==)' "$tmp"
} > requirements.txt
echo "requirements.txt: $(grep -c '==' requirements.txt) pinned packages"
